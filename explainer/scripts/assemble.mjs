// Turn audio/<beat>.wav clips into timing.js, audio/narration.wav and an updated index.html.
// Usage: node scripts/assemble.mjs   (run automatically by the TTS scripts)
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const root = new URL("..", import.meta.url);
const cfg = JSON.parse(readFileSync(new URL("narration.json", root), "utf8"));
const dur = (p) => Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", p]).toString().trim());

// Trim leading/trailing silence so beats butt up against the planned gap.
let t = 0.4;
const timing = [];
for (const b of cfg.beats) {
  const src = new URL(`audio/${b.id}.wav`, root).pathname.slice(1);
  const trimmed = src.replace(/\.wav$/, ".trim.wav");
  execFileSync("ffmpeg", ["-y", "-v", "error", "-i", src, "-af",
    `silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,atempo=${cfg.tempo ?? 1}`, trimmed]);
  const d = dur(trimmed);
  timing.push({ id: b.id, text: b.text, start: +t.toFixed(3), duration: +d.toFixed(3) });
  t += d + cfg.gap;
}
const data = { total: +(t - cfg.gap + 1.2).toFixed(3), estimated: false, beats: timing };
writeFileSync(new URL("audio/timing.json", root), JSON.stringify(data, null, 2));
writeFileSync(new URL("timing.js", root), `// generated by scripts/assemble.mjs
window.TIMING = ${JSON.stringify(data, null, 2)};
`);
// One narration track: each trimmed beat delayed to its start time.
const inputs = timing.flatMap((b) => ["-i", new URL(`audio/${b.id}.trim.wav`, root).pathname.slice(1)]);
const delays = timing.map((b, i) => `[${i}]adelay=${Math.round(b.start * 1000)}:all=1[a${i}]`).join(";");
const mix = timing.map((_, i) => `[a${i}]`).join("") + `amix=inputs=${timing.length}:normalize=0,loudnorm=I=-16:TP=-1.5:LRA=11,apad=whole_dur=${data.total}[out]`;
execFileSync("ffmpeg", ["-y", "-v", "error", ...inputs, "-filter_complex", `${delays};${mix}`, "-map", "[out]", "-ar", "44100", new URL("audio/narration.wav", root).pathname.slice(1)]);

// Point index.html at the new track and length.
const indexUrl = new URL("index.html", root);
let html = readFileSync(indexUrl, "utf8");
html = html.replace(/(id="root"[\s\S]*?data-duration=")[\d.]+(")/, `$1${data.total}$2`);
html = html.replace(/<!-- AUDIO:BEGIN -->[\s\S]*?<!-- AUDIO:END -->/,
  `<!-- AUDIO:BEGIN -->
      <audio id="vo" data-start="0" data-duration="${data.total}" data-track-index="1" src="audio/narration.wav"></audio>
      <!-- AUDIO:END -->`);
writeFileSync(indexUrl, html);

console.log(timing.map((x) => `${x.id.padEnd(11)} ${x.start.toFixed(2)}s  +${x.duration.toFixed(2)}s`).join("\n"), "\nend", (t - cfg.gap).toFixed(2));
