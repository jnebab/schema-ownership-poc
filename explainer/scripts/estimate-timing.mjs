// Placeholder timing.js from word counts (~2.7 words/sec, this voice's pace), used until the narration exists.
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("..", import.meta.url);
const cfg = JSON.parse(readFileSync(new URL("narration.json", root), "utf8"));
let t = 0.4;
const beats = cfg.beats.map((b) => {
  const d = b.text.split(/\s+/).length / 2.7;
  const beat = { id: b.id, text: b.text, start: +t.toFixed(3), duration: +d.toFixed(3) };
  t += d + cfg.gap;
  return beat;
});
const data = { total: +(t - cfg.gap + 1.2).toFixed(3), estimated: true, beats };
writeFileSync(new URL("timing.js", root), `// generated by scripts/estimate-timing.mjs\nwindow.TIMING = ${JSON.stringify(data, null, 2)};\n`);
console.log("total", data.total);
